    /**
     * A few error strings come from OMP itself. Translate the ones the app can
     * recognise, and leave anything unknown untouched instead of hiding it.
     */
    fun errorText(raw: String): String {
        val text = raw.trim()
        return when {
            text.equals("Interrupted by user", ignoreCase = true) ->
                s("Avbrutt av deg", "Interrupted by you")
            text.equals("Tool call denied by user", ignoreCase = true) ->
                s("Verktøykallet ble avslått", "Tool call denied")
            else -> text
        }
    }
